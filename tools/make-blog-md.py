#!/usr/bin/env python3
"""Собирает пакет статей для /blog/ в один markdown: порядок и три текста.

Запуск:
  python3 tools/make-blog-md.py

Отдельный файл, а не приложение к ТЗ: статьи выходят после страницы /sdelki/ и
одна из них ждёт юриста заказчика. Источник правды — docs/articles/*.md.
"""
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BASE, "docs", "Статьи-для-блога_2026-11-22.md")

ARTICLES = [
    ("Статья 1. `/blog/deal-support/` — сопровождение сделки",
     "docs/articles/2026-11-18-deal-support.md"),
    ("Статья 2. `/blog/mortgage-deal/` — ипотечная сделка",
     "docs/articles/2026-11-18-mortgage-deal.md"),
    ("Статья 3. `/blog/dkp-five-places/` — пять мест в договоре",
     "docs/articles/2026-11-18-dkp-five-places.md"),
]

HEADER = """# Статьи для `/blog/`: три текста к публикации

22 ноября 2026.

Три статьи, которые дополняют [задание по сайту](Задание-по-сайту-2026-11-22.md).
Сначала выходит `/sdelki/` с новым текстом, иначе статья ведёт на страницу,
которая ещё не отвечает на запрос. Все три выходят в один день; заказчик
смотрит после выкладки.

Ссылки на внутренние документы убраны: всё, что нужно, есть в этом файле.

## Порядок публикации

1. Сначала целевая страница `/sdelki/`: заголовки и текст из задания. Статья без
   готовой страницы работает вполовину.
2. Все три статьи — в один день. Первой выкладываем `deal-support`: на ней
   проверяем шаблон — `Article`, крошки, CTA, мобильную вёрстку. Затем
   `mortgage-deal` и `dkp-five-places`.
3. Блок «Полезное» на `/sdelki/` — сразу со всеми тремя ссылками.
4. Переобход в Вебмастере — один раз, после публикации всех трёх.

## Что нужно от раздела `/blog/`

- URL: `/blog/<slug>/`, латиница, без даты. Slug — имя файла без даты:
  `2026-11-18-deal-support.md` → `/blog/deal-support/`.
- Индексная страница `/blog/` — список с заголовками, датой и коротким лидом;
  в `sitemap.xml`.
- Шаблон статьи: H1 → дата публикации → лид → H2-разделы → блок CTA с телефоном
  → «Полезное» со ссылкой на целевую страницу услуги.
- Мета уже написана в каждой статье, менять не нужно.
- Разметка: `Article` (заголовок, дата, автор «АНВ Гарант», `publisher`) и
  `BreadcrumbList` (Главная → Блог → статья). Организацию заново не описываем:
  ссылаемся на общий блок по `@id`. `Service`, `Offer` и цены в статьях не
  ставим.
- Дата публикации — фактическая, а не 18 ноября. Все три выходят в один день;
  `datePublished` у всех — дата выхода.
- Текст в HTML целиком, без «читать далее» и аккордеонов.

## Перед публикацией

- `deal-support` читает заказчик — после выкладки: в тексте есть формулировки
  про задаток, срок регистрации и состав проверки. Если будут правки, меняем
  текст и разметку, адрес не трогаем.
- `mortgage-deal` — по желанию, там нет норм, только распределение проверок
  между банком, покупателем и продавцом.
- `dkp-five-places` написана без ссылок на законы и без норм: правка юриста её не
  блокирует.

## Что внутри

| Статья | Адрес | Ведёт на | Слов |
|---|---|---|---|
| 1 | `/blog/deal-support/` | `/sdelki/` | 1094 |
| 2 | `/blog/mortgage-deal/` | `/sdelki/` | 927 |
| 3 | `/blog/dkp-five-places/` | `/sdelki/` | 748 |

## Чего в статьях нет и не должно появиться

- Пошаговых инструкций «сделай сам»: порядок действий — это услуга, а не текст.
- Чек-листов, по которым читатель сам проверяет объект, договор или арендаторов.
- Конкретных сумм, сроков и процентов, кроме цен компании.
- Номеров форм, статей законов и названий ведомств сверх Росреестра, МФЦ и
  налоговой.
- Обещаний результата и советов по конкретному делу.
"""


def strip_first_h1(md):
    return re.sub(r"\A# [^\n]*\n+", "", md).lstrip("\n")


def plain_links(text):
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    return re.sub(r"\[([^\]]+)\]\((?!https?:)[^)]*\)", r"\1", text)


def main():
    chunks = [HEADER]
    for title, rel in ARTICLES:
        with open(os.path.join(BASE, rel), encoding="utf-8") as f:
            md = strip_first_h1(f.read()).rstrip()
        chunks.append("\n---\n")
        chunks.append(f"# {title}\n")
        chunks.append(md + "\n")

    text = plain_links("\n".join(chunks))
    text = re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("saved", OUT, len(text.split()), "слов")


if __name__ == "__main__":
    main()
